/* atan(2^-i) as a turn in 2^24 parts (CORDIC) */
static const int32_t atan_t[24] = {
	2097152, 1238021, 654136, 332050, 166669, 83416, 41718, 20860, 10430, 5215, 2608, 1304, 652, 326, 163,
	81, 41, 20, 10, 5, 3, 1, 1, 0
};

fx fx_div(fx a, fx b)
{
	int64_t q;
	if (b == 0)
		return a >= 0 ? 0x7fffffff : -0x7fffffff;
	q = (int64_t) a * 65536 / b;
	if (q > 0x7fffffff)
		return 0x7fffffff;
	if (q < -0x7fffffff)
		return -0x7fffffff;
	return (fx) q;
}

/* the sine of the first quarter: a (0 .. 16384) */
static fx sin_quarter(uint32_t a)
{
	uint32_t i = a >> 6, f = a & 63;
	int32_t s0, s1;
	if (i >= 256)
		return FX_ONE;
	s0 = sin_q[i];
	s1 = i == 255 ? FX_ONE : sin_q[i + 1];
	return s0 + (((s1 - s0) * (int32_t) f) >> 6);
}

fx fx_sin(uint32_t ang)
{
	uint32_t a = ang & 0xffff, q = a >> 14, r = a & 0x3fff;
	switch (q) {
	case 0: return sin_quarter(r);
	case 1: return sin_quarter(16384 - r);
	case 2: return -sin_quarter(r);
	default: return -sin_quarter(16384 - r);
	}
}

fx fx_cos(uint32_t ang)
{
	return fx_sin(ang + 16384);
}

uint32_t fx_atan2(fx y, fx x)
{
	int32_t ang = 0, t;
	int i;
	if (x == 0 && y == 0)
		return 0;
	/* into the right half-plane, then rotated onto the axis */
	if (x < 0) {
		x = -x;
		y = -y;
		ang = 1 << 23;		/* half a turn */
	}
	/* (kept below 2^29 so that sums don't overflow) */
	while (x > (1 << 28) || y > (1 << 28) || y < -(1 << 28)) {
		x >>= 1;
		y >>= 1;
	}
	for (i = 0; i < 24; i++) {
		if (y > 0) {
			t = x + (y >> i);
			y -= x >> i;
			x = t;
			ang += atan_t[i];
		} else {
			t = x - (y >> i);
			y += x >> i;
			x = t;
			ang -= atan_t[i];
		}
	}
	return ((uint32_t) (ang + 128) >> 8) & 0xffff;
}

uint32_t isqrt64(uint64_t v)
{
	uint64_t r = 0, bit = (uint64_t) 1 << 62;
	while (bit > v)
		bit >>= 2;
	while (bit != 0) {
		if (v >= r + bit) {
			v -= r + bit;
			r = (r >> 1) + bit;
		} else {
			r >>= 1;
		}
		bit >>= 2;
	}
	return (uint32_t) r;
}

fx fx_sqrt(fx v)
{
	if (v <= 0)
		return 0;
	return (fx) isqrt64((uint64_t) v << 16);
}

uint32_t fx_deg(fx deg)
{
	/* 65536 / 360 a degree: deg * 65536 / 360 in 16.16 */
	return (uint32_t) (((int64_t) deg * 65536 / 360) >> 16) & 0xffff;
}
